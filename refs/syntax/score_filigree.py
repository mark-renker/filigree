#!/usr/bin/env python3
"""Score Filigree against the strongest rival on each of the six benchmark tasks.

Character counts are *computed*, never typed by hand: the Filigree numbers come
from the files in `refs/syntax/filigree/`, and the rival numbers are read out of
the summary table at the top of `tasks.md`, which `build_tasks.py` generated from
the rival snippets in the same file.

Every Filigree solution is also compiled here, and a task only scores if its
solution compiles with **zero warnings** -- a snippet that does not compile is not
a solution.

    python refs/syntax/score_filigree.py            # print the scoreboard
    python refs/syntax/score_filigree.py --write    # rewrite it into tasks.md
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
TASKS = os.path.join(HERE, "tasks.md")
FIL = os.path.join(HERE, "filigree")

BEGIN = "<!-- BEGIN FILIGREE SCOREBOARD (generated by score_filigree.py) -->"
END = "<!-- END FILIGREE SCOREBOARD -->"

TITLES = {
    "T1": "4-bar minor-key ii-V-i with smooth 4-voice voicings",
    "T2": "Melody; one note bends up into the next chord's third",
    "T3": "Vibrato starting 35% into a held note, widening to the end",
    "T4": "One chord, four voices, four different pressure/timbre moves",
    "T5": "Modal-interchange substitution mid-progression",
    "T6": "One named gesture across 12 notes, one parameter changed on the 7th",
}


# Where tasks.md's "strongest rival" column is held by a snippet that does *not*
# express the whole task, the honest second comparison is the shortest rival that
# does.  These come from the prose under the summary table in tasks.md.
FULL: dict[str, tuple[str, int]] = {
    "T6": ("Sonic Pi", 157),
}


def nonspace(text: str) -> int:
    """Non-whitespace characters, comments excluded (the same rule build_tasks.py used)."""
    body = "\n".join(ln for ln in text.splitlines() if not ln.lstrip().startswith("#"))
    return len(re.sub(r"\s+", "", body))


def rivals() -> dict[str, tuple[str, int]]:
    """Read the strongest rival and its char count per task from tasks.md."""
    out: dict[str, tuple[str, int]] = {}
    # Only the rival summary table counts: stop at our own generated scoreboard,
    # whose rows would otherwise match the same shape.
    text = open(TASKS, encoding="utf-8").read().split(BEGIN)[0]
    for line in text.splitlines():
        m = re.match(r"\|\s*\*\*(T\d)\*\*.*?\|\s*([^|]+?)\s*\|\s*(\d+)\s*\|", line)
        if m:
            out[m.group(1)] = (m.group(2).strip(), int(m.group(3)))
    return out


def compiles_clean(path: str) -> tuple[bool, str]:
    env = dict(os.environ, PYTHONPATH=os.path.join(ROOT, "src"))
    p = subprocess.run([sys.executable, "-m", "filigree.cli", "explain", path],
                       cwd=ROOT, env=env, capture_output=True, text=True)
    warns = [ln for ln in p.stderr.splitlines() if "warning:" in ln]
    if p.returncode != 0:
        return False, "does not compile"
    if warns:
        return False, f"{len(warns)} warning(s)"
    return True, "compiles clean, 0 warnings"


def build() -> str:
    riv = rivals()
    rows, wins, losses, notes = [], 0, 0, []
    for tid in sorted(TITLES):
        path = os.path.join(FIL, f"{tid}.fil")
        src = open(path, encoding="utf-8").read()
        n = nonspace(src)
        ok, note = compiles_clean(path)
        rname, rn = riv.get(tid, ("?", 0))
        if not ok:
            verdict = f"**no score** ({note})"
        elif n < rn:
            verdict = f"**Filigree shorter** by {rn - n}"
            wins += 1
        elif n > rn:
            verdict = f"**{rname} shorter** by {n - rn}"
            losses += 1
        else:
            verdict = "tie"
        rows.append(f"| **{tid}** {TITLES[tid]} | "
                    f"[`filigree/{tid}.fil`]({os.path.basename(FIL)}/{tid}.fil) | "
                    f"{n} | {rname} | {rn} | {verdict} |")
        if tid in FULL:
            fname, fn = FULL[tid]
            rel = "shorter" if n < fn else "longer"
            notes.append(
                f"- **{tid}:** the {rn}-char {rname} snippet does not express the whole "
                f"task (see the {tid} section). Against the shortest rival that does "
                f"-- {fname}, {fn} chars -- Filigree's {n} chars are "
                f"{abs(n - fn)} {rel}.")

    ties = len(TITLES) - wins - losses
    tie_txt = f", {ties} tie" + ("s" if ties != 1 else "") if ties else ""
    return "\n".join([
        BEGIN,
        "",
        "## Scoreboard: Filigree vs the strongest rival on each task",
        "",
        "Generated by [`score_filigree.py`](score_filigree.py). Filigree solutions live in",
        "[`filigree/`](filigree/) as standalone files; each one is compiled by the scorer and",
        "only scores if it compiles with **zero warnings**. Counts are non-whitespace",
        "characters excluding comment lines, the same rule used for the rival snippets above.",
        "",
        "| Task | Filigree solution | chars | Strongest rival | chars | Result |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        f"**Concision record: Filigree is shorter on {wins} of {len(TITLES)} tasks and "
        f"longer on {losses}{tie_txt}.**",
        "",
        *(("One comparison needs a footnote:", "", *notes, "")
          if notes else ()),
        "The losses are real and are the interesting part. Where a rival is shorter it is",
        "because that rival has a dedicated shorthand for exactly that task and nothing",
        "else; Filigree spends its characters on a construct (`voicing`, a named gesture",
        "with parameters, a harmonic target) that is reusable across all six. Concision is",
        "only one of P1's four measures in [`../BAR.md`](../BAR.md) -- the others are",
        "expressive completeness, diff cost, and how much of the task the language can state",
        "at all. Per-task expressive verdicts are in the task sections above.",
        "",
        END,
    ])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true",
                    help="rewrite the scoreboard block inside tasks.md")
    args = ap.parse_args()
    block = build()
    if not args.write:
        print(block)
        return 0
    text = open(TASKS, encoding="utf-8").read()
    if BEGIN in text and END in text:
        pre = text.split(BEGIN)[0]
        post = text.split(END)[1]
        text = pre + block + post
    else:
        text = text.rstrip() + "\n\n---\n\n" + block + "\n"
    open(TASKS, "w", encoding="utf-8").write(text)
    print(f"wrote scoreboard into {os.path.relpath(TASKS, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
